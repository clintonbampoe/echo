using AutoFixture;
using Echo.Application.Events;
using Echo.Domain.Events;
using Echo.Domain.Members;
using Echo.Domain.Organizations;

namespace Echo.Application.Tests.Events;

[Trait("Category", "Unit")]
public class EventMapperTests
{
    private readonly IEventMapper _mapper = new EventMapper();

    /// <summary>An event with both navigation properties populated, so flattening can be verified.</summary>
    private static Event CreateEvent(Fixture fixture)
    {
        var organization = fixture.Build<Organization>().With(o => o.Name, "Grace Church").Create();
        var person = fixture.Build<Person>().With(p => p.Name, "Jane Doe").Create();
        var organizer = fixture.Build<Member>().With(m => m.Person, person).Create();

        return fixture
            .Build<Event>()
            .With(e => e.Name, "Christmas Service")
            .With(e => e.Location, "Main Hall")
            .With(e => e.Capacity, 500)
            .With(e => e.Organization, organization)
            .With(e => e.Organizer, organizer)
            .Create();
    }

    private EventCreateDto CreateDto(Fixture fixture) =>
        fixture
            .Build<EventCreateDto>()
            .With(d => d.Name, "Christmas Service")
            .With(d => d.Capacity, 100)
            .Create();

    private EventUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<EventUpdateDto>()
            .With(d => d.Name, "Easter Service")
            .With(d => d.Location, "Garden")
            .With(d => d.Capacity, 250)
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Null(entity.Organization);
        Assert.Null(entity.Organizer);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenNavigations_FromEntity()
    {
        var entity = CreateEvent(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateEvent(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateEvent(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of EventUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new EventUpdateDto();
        var entity = CreateEvent(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateEvent(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }
}
