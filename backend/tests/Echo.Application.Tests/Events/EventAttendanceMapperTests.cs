using AutoFixture;
using Echo.Application.Events;
using Echo.Domain.Events;
using Echo.Domain.Members;
using Echo.Domain.Organizations;

namespace Echo.Application.Tests.Events;

[Trait("Category", "Unit")]
public class EventAttendanceMapperTests
{
    private readonly IEventAttendanceMapper _mapper = new EventAttendanceMapper();

    /// <summary>
    /// A member whose person graph carries a readable name, so flattening
    /// <c>Member.Person.Name</c> can be verified. Every enum member is pinned: AutoFixture picks
    /// enum values at random and Verify does not scrub them, so an unpinned enum makes the snapshot
    /// differ between runs.
    /// </summary>
    private static Member CreateMember(Fixture fixture, string name) =>
        fixture
            .Build<Member>()
            .With(
                m => m.Person,
                fixture
                    .Build<Person>()
                    .With(p => p.Kind, PersonKind.Visitor)
                    .With(p => p.Name, name)
                    .Create()
            )
            .With(m => m.Gender, Gender.Female)
            .With(m => m.Region, Region.Volta)
            .With(m => m.MaritalStatus, MaritalStatus.Married)
            .With(m => m.Status, MemberStatus.Inactive)
            .Create();

    /// <summary>
    /// An event with its navigations populated and a readable name, so flattening
    /// <c>Event.Name</c> and <c>Event.StartDate</c> can be verified.
    /// </summary>
    private static Event CreateEvent(Fixture fixture, string name) =>
        fixture
            .Build<Event>()
            .With(
                e => e.Organization,
                fixture.Build<Organization>().With(o => o.Name, "Grace Church").Create()
            )
            .With(e => e.Organizer, CreateMember(fixture, "Organizer Name"))
            .With(e => e.Name, name)
            .Create();

    /// <summary>An attendance with both navigations populated, so flattening can be verified.</summary>
    private static EventAttendance CreateAttendance(Fixture fixture) =>
        fixture
            .Build<EventAttendance>()
            .With(a => a.Member, CreateMember(fixture, "Jane Doe"))
            .With(a => a.Event, CreateEvent(fixture, "Christmas Service"))
            .With(a => a.CheckInTime, new TimeOnly(9, 15))
            .Create();

    private static EventAttendanceCreateDto CreateCreateDto(Fixture fixture) =>
        fixture
            .Build<EventAttendanceCreateDto>()
            .With(d => d.CheckInTime, new TimeOnly(10, 30))
            .Create();

    private static EventAttendanceUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<EventAttendanceUpdateDto>()
            .With(d => d.CheckInTime, new TimeOnly(11, 45))
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Null(entity.Member);
        Assert.Null(entity.Event);
        Assert.Equal(default, entity.CreatedAt);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenNavigations_FromEntity()
    {
        var entity = CreateAttendance(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateAttendance(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateAttendance(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of EventAttendanceUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new EventAttendanceUpdateDto();
        var entity = CreateAttendance(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
