using AutoFixture;
using Echo.Application.Projects;
using Echo.Domain.Members;
using Echo.Domain.Projects;

namespace Echo.Application.Tests.Projects;

[Trait("Category", "Unit")]
public class ProjectMapperTests
{
    private readonly IProjectMapper _mapper = new ProjectMapper();

    /// <summary>
    /// A project with both navigation graphs populated, because ToDto flattens Category.Name and
    /// Manager.Person.Name.
    /// </summary>
    private static Project CreateProject(Fixture fixture)
    {
        var category = fixture.Build<ProjectCategory>().With(c => c.Name, "Missions").Create();
        var person = fixture.Build<Person>().With(p => p.Name, "Jane Doe").Create();
        var manager = fixture.Build<Member>().With(m => m.Person, person).Create();

        return fixture
            .Build<Project>()
            .With(p => p.Category, category)
            .With(p => p.Manager, manager)
            .With(p => p.Name, "Borehole Fund")
            .With(p => p.TargetAmount, 25_000m)
            .With(p => p.Status, ProjectStatus.OnTrack)
            .With(p => p.Description, "Clean water for the village")
            .Create();
    }

    private static ProjectCreateDto CreateDto(Fixture fixture) =>
        fixture
            .Build<ProjectCreateDto>()
            .With(d => d.CategoryId, 7)
            .With(d => d.Name, "Borehole Fund")
            .With(d => d.TargetAmount, 25_000m)
            .With(d => d.Status, ProjectStatus.OnTrack)
            .Create();

    private static ProjectUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<ProjectUpdateDto>()
            .With(d => d.CategoryId, 9)
            .With(d => d.Name, "School Roof Fund")
            .With(d => d.TargetAmount, 12_500m)
            .With(d => d.Status, ProjectStatus.AtRisk)
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids and DateTimes, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Null(entity.Category);
        Assert.Null(entity.Manager);
        Assert.Equal(default, entity.CreatedAt);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenNavigations_FromEntity()
    {
        var entity = CreateProject(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateProject(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateProject(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateProject(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of ProjectUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new ProjectUpdateDto();
        var entity = CreateProject(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
