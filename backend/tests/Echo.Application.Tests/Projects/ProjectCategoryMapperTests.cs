using AutoFixture;
using Echo.Application.Projects;
using Echo.Domain.Projects;

namespace Echo.Application.Tests.Projects;

[Trait("Category", "Unit")]
public class ProjectCategoryMapperTests
{
    private readonly IProjectCategoryMapper _mapper = new ProjectCategoryMapper();

    private static ProjectCategory CreateCategory(Fixture fixture) =>
        fixture.Build<ProjectCategory>().With(c => c.Name, "Missions").Create();

    private static ProjectCategoryCreateDto CreateDto(Fixture fixture) =>
        fixture.Build<ProjectCategoryCreateDto>().With(d => d.Name, "Missions").Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids and DateTimes, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(0, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Equal(default, entity.CreatedAt);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndOmitProjectCount_FromEntity()
    {
        var entity = CreateCategory(TestData.NewFixture());

        // ProjectCount stays at its default: the mapper ignores it because the service fills it
        // from a batched count query.
        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateCategory(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateCategory(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = TestData
            .NewFixture()
            .Build<ProjectCategoryUpdateDto>()
            .With(d => d.Name, "Community Outreach")
            .Create();
        var entity = CreateCategory(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of ProjectCategoryUpdateDto is nullable, so the default instance is
        // all-null.
        var nullDto = new ProjectCategoryUpdateDto();
        var entity = CreateCategory(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
