using AutoFixture;
using Echo.Application.Projects;
using Echo.Domain.Projects;
using Echo.Domain.Transactions;

namespace Echo.Application.Tests.Projects;

[Trait("Category", "Unit")]
public class ProjectContributionMapperTests
{
    private readonly IProjectContributionMapper _mapper = new ProjectContributionMapper();

    /// <summary>A contribution with its project set, because ToDto flattens Project.Name.</summary>
    private static ProjectContribution CreateContribution(Fixture fixture)
    {
        var project = fixture.Build<Project>().With(p => p.Name, "Borehole Fund").Create();

        return fixture
            .Build<ProjectContribution>()
            .With(c => c.Project, project)
            .With(c => c.Amount, 250m)
            .With(c => c.PaymentMethod, PaymentMethod.BankTransfer)
            .With(c => c.Description, "Monthly standing order")
            .Create();
    }

    private static ProjectContributionCreateDto CreateDto(Fixture fixture) =>
        fixture
            .Build<ProjectContributionCreateDto>()
            .With(d => d.Amount, 250m)
            .With(d => d.PaymentMethod, PaymentMethod.BankTransfer)
            .With(d => d.Description, "Monthly standing order")
            .Create();

    private static ProjectContributionUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<ProjectContributionUpdateDto>()
            .With(d => d.Amount, 400m)
            .With(d => d.PaymentMethod, PaymentMethod.MobileMoney)
            .With(d => d.Description, "Corrected amount")
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids and DateTimes, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Null(entity.Project);
        Assert.Equal(default, entity.CreatedAt);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenProjectName_FromEntity()
    {
        var entity = CreateContribution(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateContribution(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateContribution(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of ProjectContributionUpdateDto is nullable, so the default instance is
        // all-null.
        var nullDto = new ProjectContributionUpdateDto();
        var entity = CreateContribution(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
