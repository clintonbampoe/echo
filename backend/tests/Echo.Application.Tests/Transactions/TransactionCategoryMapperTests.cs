using AutoFixture;
using Echo.Application.Transactions;
using Echo.Domain.Transactions;

namespace Echo.Application.Tests.Transactions;

[Trait("Category", "Unit")]
public class TransactionCategoryMapperTests
{
    private readonly ITransactionCategoryMapper _mapper = new TransactionCategoryMapper();

    /// <summary>
    /// A category with a readable name. The enum is pinned: AutoFixture picks enum values at random
    /// and Verify does not scrub them, so an unpinned enum makes the snapshot differ between runs.
    /// </summary>
    private static TransactionCategory CreateCategory(Fixture fixture) =>
        fixture
            .Build<TransactionCategory>()
            .With(c => c.Name, "Tithes")
            .With(c => c.CategoryType, TransactionType.Expense)
            .Create();

    private static TransactionCategoryCreateDto CreateCreateDto(Fixture fixture) =>
        fixture
            .Build<TransactionCategoryCreateDto>()
            .With(d => d.Name, "Tithes")
            .With(d => d.CategoryType, TransactionType.Expense)
            .Create();

    private static TransactionCategoryUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<TransactionCategoryUpdateDto>()
            .With(d => d.Name, "First fruits")
            .With(d => d.CategoryType, TransactionType.Income)
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids and cannot tell an int key of 0 apart from
        // "left alone", so the snapshot alone would not prove these stayed untouched.
        Assert.Equal(0, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Equal(default, entity.CreatedAt);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFields_FromEntity()
    {
        var entity = CreateCategory(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToDto_ShouldNotMapTransactionCount_FromEntity()
    {
        // TransactionCategory carries no count and ToDto declares
        // [MapperIgnoreTarget(nameof(TransactionCategoryResponseDto.TransactionCount))], so the
        // count stays zero and is filled in by the caller that already counted the transactions.
        var dto = _mapper.ToDto(CreateCategory(TestData.NewFixture()));

        Assert.Equal(0, dto.TransactionCount);

        return Verify(dto);
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateCategory(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdNameAndType_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateCategory(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateCategory(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of TransactionCategoryUpdateDto is nullable, so the default instance is
        // all-null.
        var nullDto = new TransactionCategoryUpdateDto();
        var entity = CreateCategory(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
