using AutoFixture;
using Echo.Application.Transactions;
using Echo.Domain.Transactions;

namespace Echo.Application.Tests.Transactions;

[Trait("Category", "Unit")]
public class TransactionMapperTests
{
    private readonly ITransactionMapper _mapper = new TransactionMapper();

    /// <summary>
    /// A category carrying a readable name, so flattening <c>Category.Name</c> can be verified.
    /// The enum is pinned: AutoFixture picks enum values at random and Verify does not scrub them,
    /// so an unpinned enum makes the snapshot differ between runs.
    /// </summary>
    private static TransactionCategory CreateCategory(Fixture fixture) =>
        fixture
            .Build<TransactionCategory>()
            .With(c => c.Name, "Tithes")
            .With(c => c.CategoryType, TransactionType.Income)
            .Create();

    /// <summary>
    /// A transaction with its category navigation populated, so flattening can be verified. The
    /// transaction's own type differs from the category's, so the snapshot proves which one the
    /// mapper read.
    /// </summary>
    private static Transaction CreateTransaction(Fixture fixture)
    {
        var category = CreateCategory(fixture);

        return fixture
            .Build<Transaction>()
            .With(t => t.Category, category)
            .With(t => t.CategoryId, category.Id)
            .With(t => t.TransactionType, TransactionType.Expense)
            .With(t => t.Amount, 425.75m)
            .With(t => t.Description, "Sound equipment")
            .Create();
    }

    // CategoryId and Amount carry [Range], which AutoFixture honours through an engine-level node
    // that fixture registrations cannot out-prioritise, so both are pinned.
    private static TransactionCreateDto CreateCreateDto(Fixture fixture) =>
        fixture
            .Build<TransactionCreateDto>()
            .With(d => d.CategoryId, 7)
            .With(d => d.TransactionType, TransactionType.Expense)
            .With(d => d.Amount, 150.00m)
            .With(d => d.Description, "Piano lesson")
            .Create();

    private static TransactionUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<TransactionUpdateDto>()
            .With(d => d.CategoryId, 9)
            .With(d => d.TransactionType, TransactionType.Income)
            .With(d => d.Amount, 99.99m)
            .With(d => d.Description, "Reclassified")
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Null(entity.Category);
        Assert.Equal(default, entity.CreatedAt);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenNavigations_FromEntity()
    {
        var entity = CreateTransaction(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateTransaction(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateTransaction(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of TransactionUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new TransactionUpdateDto();
        var entity = CreateTransaction(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
