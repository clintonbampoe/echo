using AutoFixture;
using Echo.Application.Members;
using Echo.Domain.Members;

namespace Echo.Application.Tests.Members;

[Trait("Category", "Unit")]
public class VisitorMapperTests
{
    private readonly IVisitorMapper _mapper = new VisitorMapper();

    /// <summary>A visitor whose Person navigation is populated, so flattening can be verified.</summary>
    private static Visitor CreateVisitor(Fixture fixture)
    {
        var person = fixture
            .Build<Person>()
            .With(p => p.Kind, PersonKind.Visitor)
            .With(p => p.Name, "John Smith")
            .With(p => p.FirstName, "John")
            .With(p => p.LastName, "Smith")
            .Create();

        return fixture
            .Build<Visitor>()
            .With(v => v.Person, person)
            .With(v => v.Notes, "Came for the healing service")
            .Create();
    }

    private VisitorCreateDto CreateDto(Fixture fixture) =>
        fixture
            .Build<VisitorCreateDto>()
            .With(d => d.FirstName, "John")
            .With(d => d.LastName, "Smith")
            .With(d => d.PhoneNumber, "0244111111")
            .Create();

    private VisitorCreateDto CreateDtoWithoutPhone(Fixture fixture) =>
        fixture
            .Build<VisitorCreateDto>()
            .With(d => d.FirstName, "John")
            .With(d => d.LastName, "Smith")
            .With(d => d.PhoneNumber, (string?)null)
            .Create();

    private VisitorUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<VisitorUpdateDto>()
            .With(d => d.FirstName, "Jonathan")
            .With(d => d.LastName, "Smith-Jones")
            .With(d => d.PhoneNumber, "0555111111")
            .With(d => d.Notes, "Following up next Sunday")
            .Create();

    private MemberCreateDto CreateMemberDto(Fixture fixture) =>
        fixture
            .Build<MemberCreateDto>()
            .With(d => d.FirstName, "John")
            .With(d => d.LastName, "Smith")
            .With(d => d.PhoneNumber, "0244111111")
            .With(d => d.Gender, Gender.Male)
            .With(d => d.Region, Region.GreaterAccra)
            .With(d => d.MaritalStatus, MaritalStatus.Single)
            .With(d => d.Status, MemberStatus.Active)
            .Create();

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenNavigations_FromEntity()
    {
        var entity = CreateVisitor(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromVisitorCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var (person, visitor) = _mapper.ToEntity(dto);

        // Verify snapshots both halves of the returned tuple.
        return Verify((person, visitor));
    }

    [Fact]
    public Task ToEntity_ShouldDefaultPhoneNumberToEmptyString_FromVisitorCreateDtoWithoutPhone()
    {
        var dto = CreateDtoWithoutPhone(TestData.NewFixture());

        var (person, _) = _mapper.ToEntity(dto);

        Assert.Equal(string.Empty, person.PhoneNumber);

        return Verify(person);
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromVisitorCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var (person, visitor) = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, person.Id);
        Assert.Equal(Guid.Empty, person.CongregationId);
        Assert.Null(person.DeletedAt);
        Assert.Equal(Guid.Empty, visitor.PersonId);
        Assert.Equal(Guid.Empty, visitor.CongregationId);
        Assert.Null(visitor.DeletedAt);

        return Verify((person, visitor));
    }

    [Fact]
    public Task ToMemberEntity_ShouldMapAllFields_FromMemberCreateDto()
    {
        var dto = CreateMemberDto(TestData.NewFixture());

        return Verify(_mapper.ToMemberEntity(dto));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateVisitor(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateVisitor(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateVisitor(TestData.NewFixture());

        _mapper.Patch(dto, entity.Person, entity);

        // Visitor.Person is the Person the mapper patched, so one snapshot covers both halves.
        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of VisitorUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new VisitorUpdateDto();
        var entity = CreateVisitor(TestData.NewFixture());

        _mapper.Patch(nullDto, entity.Person, entity);

        return Verify(entity);
    }
}
