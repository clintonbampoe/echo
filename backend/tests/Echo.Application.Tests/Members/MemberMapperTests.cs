using AutoFixture;
using Echo.Application.Members;
using Echo.Domain.Members;

namespace Echo.Application.Tests.Members;

[Trait("Category", "Unit")]
public class MemberMapperTests
{
    private readonly IMemberMapper _mapper = new MemberMapper();

    /// <summary>A member whose Person navigation is populated, so flattening can be verified.</summary>
    private static Member CreateMember(Fixture fixture)
    {
        var person = fixture
            .Build<Person>()
            .With(p => p.Kind, PersonKind.Member)
            .With(p => p.Name, "Jane Doe")
            .With(p => p.FirstName, "Jane")
            .With(p => p.LastName, "Doe")
            .Create();

        return fixture
            .Build<Member>()
            .With(m => m.Person, person)
            .With(m => m.Gender, Gender.Female)
            .With(m => m.ResidentialAddress, "12 Grace Way")
            .With(m => m.City, "Kumasi")
            .With(m => m.Hometown, "Sunyani")
            .With(m => m.Region, Region.Ahafo)
            .With(m => m.MaritalStatus, MaritalStatus.Married)
            .With(m => m.NextOfKin, "Kwame Doe")
            .With(m => m.EmergencyContactName, "Ama Doe")
            .With(m => m.EmergencyContactPhoneNumber, "0244000000")
            .With(m => m.Status, MemberStatus.Active)
            .Create();
    }

    private MemberCreateDto CreateDto(Fixture fixture) =>
        fixture
            .Build<MemberCreateDto>()
            .With(d => d.FirstName, "Jane")
            .With(d => d.LastName, "Doe")
            .With(d => d.PhoneNumber, "0244000000")
            .With(d => d.Gender, Gender.Female)
            .With(d => d.Region, Region.Ahafo)
            .With(d => d.MaritalStatus, MaritalStatus.Married)
            .With(d => d.Status, MemberStatus.Active)
            .Create();

    private MemberUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<MemberUpdateDto>()
            .With(d => d.FirstName, "Janet")
            .With(d => d.LastName, "Doe-Smith")
            .With(d => d.PhoneNumber, "0555000000")
            .With(d => d.Gender, Gender.Male)
            .With(d => d.Region, Region.Volta)
            .With(d => d.MaritalStatus, MaritalStatus.Single)
            .With(d => d.Status, MemberStatus.Inactive)
            .Create();

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenNavigations_FromEntity()
    {
        var entity = CreateMember(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var (person, member) = _mapper.ToEntity(dto);

        // Verify snapshots both halves of the returned tuple.
        return Verify((person, member));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var (person, member) = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, person.Id);
        Assert.Equal(Guid.Empty, person.CongregationId);
        Assert.Null(person.DeletedAt);
        Assert.Equal(Guid.Empty, member.PersonId);
        Assert.Equal(Guid.Empty, member.CongregationId);
        Assert.Null(member.DeletedAt);

        return Verify((person, member));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateMember(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateMember(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateMember(TestData.NewFixture());

        _mapper.Patch(dto, entity.Person, entity);

        // Member.Person is the Person the mapper patched, so one snapshot covers both halves.
        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of MemberUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new MemberUpdateDto();
        var entity = CreateMember(TestData.NewFixture());

        _mapper.Patch(nullDto, entity.Person, entity);

        return Verify(entity);
    }
}
