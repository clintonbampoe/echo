using AutoFixture;
using Echo.Application.Assets;
using Echo.Domain.Assets;

namespace Echo.Application.Tests.Assets;

[Trait("Category", "Unit")]
public class AssetCategoryMapperTests
{
    private readonly IAssetCategoryMapper _mapper = new AssetCategoryMapper();

    private static AssetCategory CreateAssetCategory(Fixture fixture) =>
        fixture.Build<AssetCategory>().With(c => c.Name, "Audio Equipment").Create();

    [Fact]
    public Task ToDto_ShouldMapAllFields_FromEntity()
    {
        var entity = CreateAssetCategory(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<AssetCategoryCreateDto>()
            .With(d => d.Name, "Audio Equipment")
            .Create();

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<AssetCategoryCreateDto>()
            .With(d => d.Name, "Audio Equipment")
            .Create();

        var entity = _mapper.ToEntity(dto);

        Assert.Equal(0, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);

        return Verify(entity);
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateAssetCategory(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateAssetCategory(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = TestData
            .NewFixture()
            .Build<AssetCategoryUpdateDto>()
            .With(d => d.Name, "Lighting")
            .Create();
        var entity = CreateAssetCategory(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of AssetCategoryUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new AssetCategoryUpdateDto();
        var entity = CreateAssetCategory(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
