using AutoFixture;
using Echo.Application.Assets;
using Echo.Domain.Assets;

namespace Echo.Application.Tests.Assets;

[Trait("Category", "Unit")]
public class AssetMapperTests
{
    private readonly IAssetMapper _mapper = new AssetMapper();

    private Asset CreateAsset(Fixture fixture) =>
        fixture
            .Build<Asset>()
            .With(a => a.Name, "Yamaha Mixer")
            .With(
                a => a.Category,
                fixture.Build<AssetCategory>().With(c => c.Name, "Audio Equipment").Create()
            )
            .Create();

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenCategoryName_FromEntity()
    {
        var entity = CreateAsset(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<AssetCreateDto>()
            .With(d => d.Name, "Yamaha Mixer")
            .With(d => d.CategoryId, 7)
            .With(d => d.PurchaseCost, 1200m)
            .With(d => d.CurrentValue, 900m)
            .Create();

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<AssetCreateDto>()
            .With(d => d.Name, "Yamaha Mixer")
            .With(d => d.CategoryId, 7)
            .With(d => d.PurchaseCost, 1200m)
            .With(d => d.CurrentValue, 900m)
            .Create();

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Null(entity.Category);

        return Verify(entity);
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateAsset(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateAsset(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = TestData
            .NewFixture()
            .Build<AssetUpdateDto>()
            .With(d => d.Name, "Roland Keyboard")
            .With(d => d.CategoryId, 9)
            .With(d => d.PurchaseCost, 800m)
            .With(d => d.CurrentValue, 750m)
            .Create();
        var entity = CreateAsset(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of AssetUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new AssetUpdateDto();
        var entity = CreateAsset(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
