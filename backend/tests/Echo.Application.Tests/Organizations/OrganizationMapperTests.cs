using AutoFixture;
using Echo.Application.Organizations;
using Echo.Domain.Organizations;

namespace Echo.Application.Tests.Organizations;

[Trait("Category", "Unit")]
public class OrganizationMapperTests
{
    private readonly IOrganizationMapper _mapper = new OrganizationMapper();

    private static Organization CreateOrganization(Fixture fixture) =>
        fixture.Build<Organization>().With(o => o.Name, "Choir").Create();

    [Fact]
    public Task ToDto_ShouldMapAllFields_FromEntity()
    {
        var entity = CreateOrganization(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<OrganizationCreateDto>()
            .With(d => d.Name, "Choir")
            .Create();

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<OrganizationCreateDto>()
            .With(d => d.Name, "Choir")
            .Create();

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);

        return Verify(entity);
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateOrganization(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateOrganization(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = TestData
            .NewFixture()
            .Build<OrganizationUpdateDto>()
            .With(d => d.Name, "Usher Team")
            .With(d => d.Description, "Front of house")
            .Create();
        var entity = CreateOrganization(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of OrganizationUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new OrganizationUpdateDto();
        var entity = CreateOrganization(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
