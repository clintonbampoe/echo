using AutoFixture;
using Echo.Application.Organizations;
using Echo.Domain.Members;
using Echo.Domain.Organizations;

namespace Echo.Application.Tests.Organizations;

[Trait("Category", "Unit")]
public class OrganizationMemberMapperTests
{
    private readonly IOrganizationMemberMapper _mapper = new OrganizationMemberMapper();

    private OrganizationMember CreateOrganizationMember(Fixture fixture)
    {
        var member = fixture
            .Build<Member>()
            .With(
                m => m.Person,
                fixture.Build<Person>().With(p => p.Name, "Jane Doe").Create()
            )
            .Create();
        var organization = fixture.Build<Organization>().With(o => o.Name, "Choir").Create();

        return fixture
            .Build<OrganizationMember>()
            .With(m => m.Member, member)
            .With(m => m.Organization, organization)
            .Create();
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenMemberAndOrganizationNames_FromEntity()
    {
        var entity = CreateOrganizationMember(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<OrganizationMemberCreateDto>()
            .With(d => d.JoinedAt, new DateOnly(2026, 3, 1))
            .Create();

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<OrganizationMemberCreateDto>()
            .With(d => d.JoinedAt, new DateOnly(2026, 3, 1))
            .Create();

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Null(entity.Member);
        Assert.Null(entity.Organization);

        return Verify(entity);
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateOrganizationMember(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = TestData
            .NewFixture()
            .Build<OrganizationMemberUpdateDto>()
            .With(d => d.Role, MemberRole.Leader)
            .With(d => d.JoinedAt, new DateOnly(2026, 5, 4))
            .Create();
        var entity = CreateOrganizationMember(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of OrganizationMemberUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new OrganizationMemberUpdateDto();
        var entity = CreateOrganizationMember(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
