using AutoFixture;
using Echo.Application.Users;
using Echo.Domain.Users;

namespace Echo.Application.Tests.Users;

[Trait("Category", "Unit")]
public class UserMapperTests
{
    private readonly IUserMapper _mapper = new UserMapper();

    private static User CreateUser(Fixture fixture) =>
        fixture
            .Build<User>()
            .With(u => u.Name, "Jane Doe")
            .With(u => u.EmailAddress, "jane@echo.test")
            .Create();

    private static UserCreateDto CreateDto(Fixture fixture) =>
        fixture
            .Build<UserCreateDto>()
            .With(d => d.FirstName, "Jane")
            .With(d => d.LastName, "Doe")
            .With(d => d.EmailAddress, "jane@echo.test")
            .With(d => d.Password, "Password123!")
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFields_FromEntity()
    {
        var entity = CreateUser(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToAuthDto_ShouldMapAllFields_FromEntity()
    {
        var entity = CreateUser(TestData.NewFixture());

        return Verify(_mapper.ToAuthDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateUser(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdNameAndEmail_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateUser(fixture));

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = TestData
            .NewFixture()
            .Build<UserUpdateDto>()
            .With(d => d.EmailAddress, "new@echo.test")
            .With(d => d.Password, "NewPassword123!")
            .With(d => d.Role, UserRole.Admin)
            .Create();
        var entity = CreateUser(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of UserUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new UserUpdateDto();
        var entity = CreateUser(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
