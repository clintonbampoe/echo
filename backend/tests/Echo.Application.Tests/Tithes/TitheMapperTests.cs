using AutoFixture;
using Echo.Application.Tithes;
using Echo.Domain.Members;
using Echo.Domain.Tithes;
using Echo.Domain.Transactions;

namespace Echo.Application.Tests.Tithes;

[Trait("Category", "Unit")]
public class TitheMapperTests
{
    private readonly ITitheMapper _mapper = new TitheMapper();

    /// <summary>
    /// A member whose person graph carries readable names, so flattening <c>Member.Person.Name</c>
    /// can be verified. Every enum member is pinned: AutoFixture picks enum values at random and
    /// Verify does not scrub them, so an unpinned enum makes the snapshot differ between runs.
    /// </summary>
    private static Member CreateMember(Fixture fixture, string name) =>
        fixture
            .Build<Member>()
            .With(
                m => m.Person,
                fixture
                    .Build<Person>()
                    .With(p => p.Kind, PersonKind.Visitor)
                    .With(p => p.Name, name)
                    .Create()
            )
            .With(m => m.Gender, Gender.Female)
            .With(m => m.Region, Region.Volta)
            .With(m => m.MaritalStatus, MaritalStatus.Married)
            .With(m => m.Status, MemberStatus.Inactive)
            .Create();

    /// <summary>A tithe with its member navigation populated, so flattening can be verified.</summary>
    private static Tithe CreateTithe(Fixture fixture) =>
        fixture
            .Build<Tithe>()
            .With(t => t.Member, CreateMember(fixture, "Jane Doe"))
            .With(t => t.Amount, 250.50m)
            .With(t => t.ForYear, 2026)
            .With(t => t.ForMonth, MonthOfYear.March)
            .With(t => t.PaymentMethod, PaymentMethod.MobileMoney)
            .With(t => t.Description, "Sunday offering")
            .Create();

    // Amount and ForYear carry [Range], which AutoFixture honours through an engine-level node
    // that fixture registrations cannot out-prioritise, so both are pinned.
    private static TitheCreateDto CreateCreateDto(Fixture fixture) =>
        fixture
            .Build<TitheCreateDto>()
            .With(d => d.Amount, 120.25m)
            .With(d => d.ForYear, 2025)
            .With(d => d.ForMonth, MonthOfYear.November)
            .With(d => d.PaymentMethod, PaymentMethod.Cash)
            .With(d => d.Description, "Monthly tithe")
            .Create();

    private static TitheUpdateDto CreateUpdateDto(Fixture fixture) =>
        fixture
            .Build<TitheUpdateDto>()
            .With(d => d.Amount, 300.75m)
            .With(d => d.ForYear, 2027)
            .With(d => d.ForMonth, MonthOfYear.September)
            .With(d => d.PaymentMethod, PaymentMethod.BankTransfer)
            .With(d => d.Description, "Revised note")
            .Create();

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = CreateCreateDto(TestData.NewFixture());

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Equal(Guid.Empty, entity.CongregationId);
        Assert.Null(entity.Member);
        Assert.Equal(default, entity.CreatedAt);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToDto_ShouldMapAllFieldsAndFlattenNavigations_FromEntity()
    {
        var entity = CreateTithe(TestData.NewFixture());

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var fixture = TestData.NewFixture();
        var entities = TestData.Many(3, () => CreateTithe(fixture));

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateTithe(TestData.NewFixture());

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of TitheUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new TitheUpdateDto();
        var entity = CreateTithe(TestData.NewFixture());

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldKeepTheMember_WhenDtoHasValues()
    {
        // The member a tithe belongs to is fixed when it is recorded, so the update DTO carries no
        // member and Patch must leave both the id and the navigation untouched.
        var dto = CreateUpdateDto(TestData.NewFixture());
        var entity = CreateTithe(TestData.NewFixture());
        var member = entity.Member;

        _mapper.Patch(dto, entity);

        Assert.Same(member, entity.Member);

        return Verify(entity);
    }
}
