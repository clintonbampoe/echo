using AutoFixture;
using Echo.Application.Congregations;
using Echo.Domain.Congregations;

namespace Echo.Application.Tests.Congregations;

[Trait("Category", "Unit")]
public class CongregationMapperTests
{
    private readonly ICongregationMapper _mapper = new CongregationMapper();

    [Fact]
    public Task ToDto_ShouldMapAllFields_FromEntity()
    {
        var entity = TestData.NewFixture().Create<Congregation>();

        return Verify(_mapper.ToDto(entity));
    }

    [Fact]
    public Task ToEntity_ShouldMapAllFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<CongregationCreateDto>()
            .With(d => d.Name, "Grace Church")
            .Create();

        return Verify(_mapper.ToEntity(dto));
    }

    [Fact]
    public Task ToEntity_ShouldNotOverrideAutoGeneratedFields_FromCreateDto()
    {
        var dto = TestData
            .NewFixture()
            .Build<CongregationCreateDto>()
            .With(d => d.Name, "Grace Church")
            .Create();

        var entity = _mapper.ToEntity(dto);

        // Asserted explicitly: Verify scrubs Guids, so a snapshot cannot distinguish
        // "left empty" from "assigned".
        Assert.Equal(Guid.Empty, entity.Id);
        Assert.Null(entity.DeletedAt);

        return Verify(entity);
    }

    [Fact]
    public Task ToListDto_ShouldMapAllFields_FromEntityList()
    {
        var entities = TestData.NewFixture().CreateMany<Congregation>(3).ToList();

        return Verify(_mapper.ToListDto(entities));
    }

    [Fact]
    public Task ToSearchDto_ShouldMapIdAndName_FromEntityList()
    {
        var entities = TestData.NewFixture().CreateMany<Congregation>(3).ToList();

        return Verify(_mapper.ToSearchDto(entities));
    }

    [Fact]
    public Task Patch_ShouldApplyAllFieldsInDto_ToEntity()
    {
        var dto = TestData
            .NewFixture()
            .Build<CongregationUpdateDto>()
            .With(d => d.Name, "Grace Chapel")
            .With(d => d.City, "Kumasi")
            .Create();
        var entity = TestData.NewFixture().Create<Congregation>();

        _mapper.Patch(dto, entity);

        return Verify(entity);
    }

    [Fact]
    public Task Patch_ShouldIgnoreAllNullFieldsInDto()
    {
        // Every member of CongregationUpdateDto is nullable, so the default instance is all-null.
        var nullDto = new CongregationUpdateDto();
        var entity = TestData.NewFixture().Create<Congregation>();

        _mapper.Patch(nullDto, entity);

        return Verify(entity);
    }
}
